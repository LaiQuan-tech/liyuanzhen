/**
 * 一個「姿勢」＝一張底圖 ＋ 它專屬的 poster ＋ 影片框的位置。
 *
 * 🔴 這三樣是**不可分割的一組**。之前 poster 是 LiveStage 手寫的字串、幾何在
 * 這個檔案裡，靠註解維繫——換底圖忘了換 poster，串流接上的瞬間臉會跳，
 * 而畫面上看不出原因。收進同一個物件之後，這個錯誤就變成型別問題。
 *
 * ⚠️ 加新姿勢不是「填四個數字」。底圖 JPEG 本身必須先把 poster 的臉用同一個
 * 橢圓烘進去（CSS 用 r=1，圖檔要烘到 1.02→1.12），否則會出現「一張臉有兩層」；
 * poster 也要先套 -gamma 1.175 並把背景壓回 rgb(233,237,236)。
 * 程式碼的改動是小工程，圖檔的製作才是大工程。作法全寫在下面各段註解裡。
 */
export interface Pose {
  /** 全身底圖（9:16，1080×1920）。臉已經烘進去了。 */
  src: string;
  /** 串流接上前鋪的靜態臉。⚠️ 必須跟 src 是同一次烘出來的那一組。 */
  poster: string;
  /** 串流影片在舞台框裡的位置，單位是舞台框的百分比。 */
  box: { left: string; top: string; width: string; height: string };
  /**
   * 鋪滿整個視窗的背景圖。沒有這個欄位就維持原本的純色底。
   *
   * 🔴 有 `background` 的姿勢，`src` **必須是帶 alpha 的去背檔**，兩者是一組。
   * 只換其中一邊的後果很具體：給了背景卻用不透明的 JPEG，畫面上會是一張
   * 灰色長方形貼在街景中間；給了去背檔卻沒有背景，她會浮在 #1A1A1A 上。
   * `lib/live/pose.test.ts` 有一條在守這件事。
   */
  background?: string;
}

