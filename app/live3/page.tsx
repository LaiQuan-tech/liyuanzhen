/**
 * `/live` 的第三個版本：人物跟 `/live2` 一模一樣（站著、捧著一本翻開的書），
 * 差別只有背景——棚拍的純灰換成一張真實街景，而且左右滿版沒有黑邊。
 *
 * 頁面本身跟 `/live`、`/live2` 一樣是一層薄殼，同樣**刻意不掛** `<Nav />` 與
 * `<Footer />`——這一頁的重點就是那個佔滿螢幕的人，上下各一條列會把它切碎。
 * 代價是頁首頁尾常駐的揭露不會跟過來，所以 LiveStage 自己把 AVATAR_NAME、
 * ANSWER_DISCLAIMER、SITE_NOTICE 與影片上的常駐浮水印全部放回畫面上。
 * 那不是可選的裝飾，見該元件的檔頭。
 *
 * ⚠️ 它跟 `/live2` **共用同一組人物幾何**（`POSE_STANDING_STREET.box` 直接引用
 * `POSE_STANDING.box`）。要調對位就是兩頁一起調，不要只改一邊。
 *
 * 🔴 三頁各自會開一個**計費中**的 LiveAvatar session。同時開著就是三份錢。
 *
 * ---
 *
 * ## 背景板 `public/live-bg-street.webp` 是怎麼做出來的
 *
 * 來源是使用者提供的原檔 `1930.jpg`（1560×1170，她站在店門口的那張）。
 *
 * 🔴 **背景板必須是橫的、≥16:9**，這是第一版做錯過的地方。
 * 去背之後背景會從她身體以外的**每一個像素**透出來（含 9:16 框裡面），
 * 所以 `object-cover` 的行為決定一切：直式的板子在 1920×1080 上要放大 4.42 倍、
 * 只露出來源高度的 31.8%，那一段實測 `mean 136 / sd 20`——就是木門那片平板，
 * 桌機上會看到一片糊斑。16:9 的板子在手機(0.46)、iPad(0.75)、筆電(1.6)、
 * 桌機(1.778) 全部顯示完整高度，垂直取景才跨裝置穩定。
 *
 * 🔴 **地平面必須延伸到圖高 85% 以上**，否則某些視窗尺寸下她會浮空。
 * 她的腳底位置算得出來：`(H_vp − H_frame)/2 + 0.9802·H_frame`，其中
 * `H_frame = min(H_vp, W_vp×16/9)`。桌機是視窗高的 97.97%、390×844 手機是 89.4%。
 *
 * 作法（原圖左半是她本人，直接裁右半會丟掉使用者要的藍色鐵柵欄）：
 *   1. 取 `x≥850` 當基本塊（藍柱＋木門＋地面，唯一髒的是左下角她的外套）
 *   2. 外套用**鏡射真實像素**修掉（以 x=270 為鏡面），這是 repo 驗證過的方法
 *      （commit 0667883）：不平滑、不加雜訊。同一則 commit 記著三種失敗——
 *      只換亮 22 階以上的像素會留鬼影、中值濾波 size 15 會把細節一起糊掉、
 *      垂直內插＋雜訊＋羽化看得出補過
 *   3. 左右鏡射拼接到 2080×1170（16:9）。鏡面接縫是連續的，而且每一塊的
 *      垂直結構相同，所以地平線自動跨整張圖對齊
 *   4. 放大到 2560×1440 → **明確失焦**（高斯 11）→ 整體壓到 60% →
 *      底部由下往上加深、頂部輕微加深 → WebP q90（48 KB）
 *
 * ⚠️ 第 4 步的壓暗與烘漸層是**刻意做在圖檔上、不是調 CSS**。
 * `LiveStage` 底部那條 `from-ink via-ink/85 to-transparent` 是字幕可讀性的唯一
 * 保障（主字幕是 17–20px 純白、零底色零描邊；SITE_NOTICE 只有 10px、
 * `text-white/35`，而那是法定揭露）。算過：白字壓在 `ink/45` 上、底下是中間調
 * (L136) → 6.9:1 可以，但原圖有亮區（木門高光約 200、水泥緣石約 250），
 * 白字壓在 `ink/45` 上、底下 L250 → **2.4:1 不及格**。所以不能為了多露一點
 * 街景而把漸層調淡；把板子壓暗（最亮值從 250 降到 121）才是對的方向。
 *
 * 人物去背的作法在 `components/avatar/poses.ts` 的 `POSE_STANDING_STREET`。
 */
