/**
 * 判斷逐字稿裡到底有沒有「話」。
 *
 * 🔴 存在的理由是實際發生的事：正式站的 interactions 表裡有 8 筆問題是
 * 「00:00」、還有一筆是「3」。那是 Gemini 的語音辨識把靜音或環境噪音
 * 轉成了時間碼／數字，前端照樣把它當成問題送進 /api/chat。
 *
 * 每一筆的代價：白花一次 Gemini 呼叫、佔一次限流額度、在問答紀錄裡留下一筆
 * 沒有意義的資料，而訪客那邊看到的是一段莫名其妙的婉拒——他會以為是自己問錯了。
 *
 * ⚠️ 空字串已經在 LiveStage 裡處理了（走 liveCopy.heardNothing），這一支處理的是
 * 另一種情況：**有字，但那些字不構成話**。兩者的使用者提示相同，
 * 因為對使用者來說是同一件事：她沒聽出內容，再說一次。
 */

/**
 * 至少要有一個「表意」字元才算是話：中日文字，或拉丁字母。
 *
 * ⚠️ 判準刻意是「有沒有」而不是「佔多少比例」。
 * 「1982 年為什麼辦婦女新知」數字佔了一半，但它是個好問題；
 * 而「00:00」一個表意字元都沒有。用比例會誤傷前者。
 */
/* ⚠️ 用明確碼位範圍而不是 \p{Script=Han}：後者需要 ES2018 以上，
   而這個專案的 tsconfig target 比它低，會編不過。 */
const MEANINGFUL =
  /[a-zA-Z\u3040-\u309f\u30a0-\u30ff\u3400-\u4dbf\u4e00-\u9fff]/;

/**
 * 這段逐字稿值不值得送去問？
 *
 * ⚠️ 判斷要盡量寬鬆——誤擋一個真的問題，比放行一筆垃圾嚴重得多。
 * 所以只擋「完全沒有表意字元」這一種，不做語意判斷。
 */
export function looksLikeSpeech(transcript: string): boolean {
  const t = transcript.trim();
  if (!t) return false;
  return MEANINGFUL.test(t);
}
