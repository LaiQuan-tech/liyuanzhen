  "(?:小時候|從小|的時候|那時候|那年|那一年|當年|當時|以前|從前|早年|那時|那陣子|那段(?:時間|日子|期間)|歲(?:那年|時|的時候)|童年|幼年|年幼|還小|很小|出生|嬰兒|襁褓|國小|小學|國中|初中|高中|大學|幼稚園|幼兒園|托兒所|讀書|念書|求學|上學)";
const DAUGHTER_HEALTH_FAITH =
  "(?:癲癇|癲癎|住院|住進醫院|病情|生病|信了?教(?!育|學|書|授|材|師|練|導|室|科)|基督|受洗|教會(?!了?[她他我你妳您們]|學))";
const DAUGHTER_LIVING = "(?:房租|匯款|獨居|一個人住)";
/** 同一句裡、不在往事標記上的字；bare 版另外不准有「你」 */
const IN_SENTENCE_NO_PAST = `(?:(?!${PAST_MARK})[^。！？\\n])`;
const IN_SENTENCE_NO_PAST_NO_YOU = `(?:(?!${PAST_MARK})[^。！？\\n你妳您])`;
function daughterNews(status: string, span: number): RegExp[] {
  const s = IN_SENTENCE_NO_PAST;
  const b = IN_SENTENCE_NO_PAST_NO_YOU;
  return [
    // 「我（的）女兒」「我家（的）女兒」
    new RegExp(`(?:^|[。！？\\n])${s}*?我(?:的|家的?)?女兒${s}{0,${span}}?${status}${s}*[。！？\\n]`),
    // 沒有別的所有者的「女兒」（句首，或前一個字不是你妳您他她們的家我——「他家女兒」「朋友的女兒」是別人的）
    new RegExp(`(?:^|[。！？\\n])(?:${b}*?[^你妳您他她們的家我。！？\\n])?女兒${b}{0,${span}}?${status}${b}*[。！？\\n]`),
  ];
}

/**
 * 在世家人的隱私與老師近況。命中時 kind 是 "privacy"。
 *
 * 🔴 2026-09-28 第十輪：從 BLOCKED_PATTERNS 抽出來。原本命中時跟政治表態共用 GUARDED_REPLY——
 * 「這部分我不方便表態」回給「我覺得妳好可憐 一個人都沒人照顧」「妳女兒信什麼教」是答非所問。
 * 現在 route 送 content/site.ts 的 PRIVACY_REPLY（「謝謝你的關心。老師本人和家人現在的生活，我是 AI 分身，
 * 沒辦法代替她們說明…」）。checkAnswer 仍然檢查，而且排在 LEAK_PATTERNS、BLOCKED_PATTERNS 之後：
 * 同一段答案兩種都中時照舊算 leak／pattern（推理外洩、政治表態那句優先）。
 *
 * 🔴 第十三輪換做法：敏感段落改在語料層用排除標記不進檢索，護欄只當最後一道，**只留高精確度的樣式——
 * 寧可漏，也不誤攔往事**。前幾輪為了補漏接一路加的規則，兩頭都在漏：
 * 誤攔往事（「現在回想，我們一家人住在一起的那兩三年…」「如今想起，我和女兒在淡水同住的日子…」
 * 「1957 年搬到花蓮後，和妹妹們一起住在花園洋房裡」），換個說法的洩漏又攔不到。所以拿掉了：
 * 時間詞開頭的同住（「現在回想」「如今想起」會誤觸發）、「搬到…和妹妹…一起住」、跟近年標記連動的跌倒。
 * 「我 2021 年在花蓮跌倒」這類變形交給語料排除，不在這裡追。每一條的出處與反例見測試。
 * ⚠️ 下面每一條都是「講出來就一定是近況或家人隱私」的寫法；要加新的，先逐句掃語料，確認一句往事都不會中。
 */
export const PRIVACY_PATTERNS: RegExp[] = [
  // 現居：南港國宅（07:356、09:281）、住進國宅。⚠️ 家裡第一棟房子「松山國宅」（08:195）是歷史，
  // 「一起住進松山國宅」中間夾了地名，不會中
  /南港國宅|住進國宅/,
  // 老師近年的健康：記憶退化、失智、輪椅（07:348–352，已排除出檢索）。第十五輪起只收她本人明確自述現在有的寫法，
  // 「我」後面只准接白名單的字（SELF_HEALTH_GAP）、健康字眼後面也是白名單（SELF_HEALTH_TAIL），理由與代價見那兩個常數。
  new RegExp(`我(?!們)${SELF_HEALTH_GAP}{1,6}(?:記憶力?(?:開始)?退化|失智|輪椅)${SELF_HEALTH_TAIL}`),
  // 女兒的健康與信仰（09:275–287、10:35–37）、女兒現在的生活：一個人住、獨居、收房租、匯款（09:281）。
  // 第十五輪：只收她的女兒＋近況、整句沒有往事標記，理由見 daughterNews 上方
  ...daughterNews(DAUGHTER_HEALTH_FAITH, 15),
  ...daughterNews(DAUGHTER_LIVING, 12),
  // 現在的照顧安排
  /照顧我的(生活)?起居/,
  new RegExp(`(妹妹|元晶)(現在|目前)[^。！？]{0,8}?(同住|住一起|${CARES_FOR_ME})`),
];

/**
 * 封鎖清單的三類：pattern＝政治表態、新承諾、新書資訊；leak＝推理外洩（第十五輪分出來，route 送 FALLBACK_REPLY、記 failed）；
 * privacy＝在世家人隱私與老師近況
 */
export type PatternKind = "pattern" | "leak" | "privacy";

/** 攔截屬於哪一類（finish() 回傳）：route.ts 靠它選替代回覆 */
export type GuardKind = PatternKind | "grounding";

export interface GuardResult {
  text: string;
  blocked: boolean;
  matched?: string;
  /** blocked 時才有 */
  kind?: PatternKind;
}

export function checkAnswer(text: string): GuardResult {
  // 順序：推理外洩 → 政治表態等 → 隱私（同一段同時命中時的歸類，理由見 LEAK_PATTERNS 上方）
  for (const pattern of LEAK_PATTERNS) {
    const m = text.match(pattern);
    if (m) return { text, blocked: true, matched: m[0], kind: "leak" };
  }
  for (const pattern of BLOCKED_PATTERNS) {
    const m = text.match(pattern);
    if (m) return { text, blocked: true, matched: m[0], kind: "pattern" };
  }
  for (const pattern of PRIVACY_PATTERNS) {
    const m = text.match(pattern);
    if (m) return { text, blocked: true, matched: m[0], kind: "privacy" };
  }
  return { text, blocked: false };
}

/** 語音朗讀會把符號唸出來，所以殘留的 Markdown 一律清掉 */
export function stripMarkdown(text: string): string {
  return text
    .replace(/```[\s\S]*?```/g, "")
    .replace(/(\*\*|__)(.*?)\1/g, "$2")
    .replace(/(^|\s)[*_](\S[^*_]*)[*_]/g, "$1$2")
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/^\s*[-*+]\s+/gm, "")
    .replace(/`([^`]+)`/g, "$1");
}

/**
 * 逗號類標點（，、；：）後面的換行拿掉，連同換行前後的空白。createGuardedWriter 在 emit 之前對扣住的文字做
 * （跟 stripMarkdown 同一層）；落地檢查、封鎖清單與紀錄用的原文（full）不經過這裡。
 *
 * 🔴 第十五輪（本機評測）：模型有時在每個逗號後面換行，T-08 原答是
 * 「資料裡記載的是，\n我談到 1987 年華西街遊行時，\n曾說過，\n「麥克風要在女人手上」，\n…」——
 * 文字版一句一行，字幕也跟著斷成一行一行。
 * ⚠️ 句號、問號、驚嘆號後面的換行與空行都保留：逐字念詩時，詩行之間的換行不可以被合併（詩行尾大多沒有標點）。
 * 逗號後面接的是空行（兩個換行）也保留。
 * ⚠️ 代價，不要假裝沒有：語料裡少數詩行本身以逗號收尾——剝掉排除區後抽查，詩的短行 705 行裡有 20 行（2.8%）以「，、；：」結尾，
 * 分布在 10 首（例如 10-autobiography-07.md 的「每日拉開西窗百葉，」「蔥綠橫臥的美崙山，」、05 的「山坡，山坡，」），
 * 逐字念那幾首時，那幾行會跟下一行接成一行。引詩前的「：\n」也會接起來（「我寫過：不再是自戀的水仙了…」）。
 * ⚠️ 換行後面一定要真的出現下一個字才接（串流：「，\n」停在扣住的文字結尾時先不動，等下一段進來）。
 */
export function joinSoftBreaks(text: string): string {
  return text.replace(/([，、；：])[^\S\n]*\n[^\S\n]*(?=\S)/g, "$1");
}

