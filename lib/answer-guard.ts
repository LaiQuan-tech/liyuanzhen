export function groundingCheck(text: string, context: GuardContext): GroundingVerdict {
  // ⚠️ 站方說法（SITE_PHRASES／SITE_FAQ_LINES）刻意**不**放進比對語境，只在 stripMetaClauses 裡用來認出站方認可的說法——理由見 SITE_PHRASES。
  // 反過來，比對語境會傳進 stripMetaClauses：對得上這次檢索內容的站方說法不剝，理由見 siteSplit。
  const contextCjk = cjkOnly(
    [context.question, ...context.chunks.flatMap((c) => [c.title, c.content])].join("\n")
  );

  // 三個放行來源，缺一不可——各自擋掉的是不同的東西：
  //   context      這次真的檢索到的塊（含訪客自己在問句裡講出的篇名）。
  //                少了它，模型照著眼前資料引用反而被攔。
  //   KNOWN_TITLES 語料裡出現過但這次沒檢索到的標題（《婦女新知》《民法．親屬編》…）。
  //                少了它，罐頭句與她講了幾十年的法條都會被誤判成編造。
  //   OWN_BOOKS    她自己的書。prompt 規則 9 主動要求她把人帶到書上，
  //                而《我來了》這個簡稱在語料標題裡找不到（語料寫的是全名）。
  //                少了它，等於在罰她照規則做事。
  for (const cite of citations(text)) {
    if (OWN_BOOKS.some((b) => cite.title.startsWith(b))) continue;
    if (contextCjk.includes(cite.title)) continue;
    if (KNOWN_TITLE_SET.has(cite.title)) continue;
    return { blocked: true, reason: `未落地引用：${cite.raw}`, rate: null };
  }

  // 價格與 ISBN 的數字要在這次檢索到的參考資料裡找得到（理由見 PRICE_NUMBER）。跟引用落地一樣不看 chunks 是不是空的。
  // ⚠️ 攔截原因不可以用「落地率」開頭：route 的專線救援只接落地率不足。
  const price = unsupportedPrice(text, context.chunks);
  if (price) return { blocked: true, reason: `未落地數字：${price}`, rate: null };

  // 跳過條件。每一條都要有理由，見上面各常數的註解。
  if (context.chunks.length === 0) {
    // 沒有檢索到任何東西，落地率對誰都是 0，算了也只是一律封鎖
    return { blocked: false, rate: null, skipped: "沒有檢索到參考資料" };
  }
  // ⚠️ 這裡原本有「含婉拒標記就整段跳過」。2026-09-25 改成在 stripMetaClauses 裡逐子句剝，理由見 DECLINE_MARKERS。

  // 先剝否認／歸屬句（理由見 DENIAL_SENTENCE），再剝固定用語，剩下的才是要落地的實質主張
  const core = stripBoilerplate(cjkOnly(stripDenials(text)));
  if (core.length < MIN_CHARS) {
    return { blocked: false, rate: null, skipped: `剝掉固定用語後只剩 ${core.length} 字` };
  }

  // 再剝元語言子句（理由見 META_CLAUSE）。⚠️ 上面「是不是短答案」刻意用剝元語言之前的 core 判斷，
  // 剝完只看有沒有剩下一個主張子句的長度——兩個門檻為什麼不同，見 MIN_CLAIM_CHARS。
  // 逐字記下「是不是元語言子句裡留下來的填充字」（見 MIN_CONTENT_PER_HIT）。一般的主張句全部是 false，算法跟以前一樣
  let joined = "";
  let joinedFlags: boolean[] = [];
  for (const seg of metaClaimSegments(stripDenials(text), contextCjk)) {
    const cjk = cjkOnly(seg.text);
    joined += cjk;
    joinedFlags = joinedFlags.concat(seg.partial ? fillerPositions(cjk) : cjk.split("").map(() => false));
  }
  const aligned = stripBoilerplateAligned(joined, joinedFlags);
  const claims = aligned.text;
  if (claims.length < MIN_CLAIM_CHARS) {
    return { blocked: false, rate: null, skipped: `剝掉元語言子句後只剩 ${claims.length} 字` };
  }

  const questionCjk = cjkOnly(context.question);
  let hit = 0;
  const total = claims.length - NGRAM + 1;
  for (let i = 0; i < total; i += 1) {
    const gram = claims.slice(i, i + NGRAM);
    if (!contextCjk.includes(gram)) continue;
    let content = 0;
    for (let k = i; k < i + NGRAM; k++) if (!aligned.flags[k]) content += 1;
    // 重述訪客問句的不受這條限制（理由見 MIN_CONTENT_PER_HIT）
    if (content >= MIN_CONTENT_PER_HIT || questionCjk.includes(gram)) hit += 1;
  }
  const rate = hit / total;

  if (rate < GROUNDING_FLOOR) {
    return { blocked: true, reason: `落地率 ${Math.round(rate * 100)}%`, rate };
  }
  return { blocked: false, rate };
}

/**
 * 🔴 60 → 140 是為了讓落地檢查來得及。
 *
 * 落地檢查要拿**整段**答案才算得出來，所以只能放在 finish()。但字一旦 emit 出去
 * 就收不回來（見 lib/avatar/types.ts 的 speakableAnswer：那是這個專案的老坑）。
 * lib/persona-prompt.ts 規則 8 把回答上限定在 100 字，緩衝 ≥ 140 等於
 * 「整段看完再吐出」，finish() 的檢查實質上變成吐出前檢查。
 *
 * 取捨：
 * - 數位人（/live 系列）本來就在串流結束後才用
 *   `finish(speakableAnswer(full, GUARDED_REPLY))` 開口，時機完全不變。
 *   逐句朗讀的 monogram driver 反而變安全了——它現在也是整段才收到。
 * - /chat 文字版會從「逐字出現」變成「約 100 字一次出現」，延遲等於生成時間
 *   （1–2 秒）。這是知情的取捨：用打字機效果換一層守門。
 *
 * ⚠️ 殘餘風險，不要假裝沒有：100 字是 prompt 上限，不是硬限制，模型偶爾會超過。
 * 超過 140 的部分仍然會先吐出去；此時 finish 攔下的話 /chat 會看到半段＋罐頭句，
 * 數位人端由 speakableAnswer 處理（結尾是 content/site.ts 的 TAIL_REPLIES 其中一句，就只講那一句）。
 */
const BUFFER_CHARS = 140;

/**
 * 滾動緩衝的串流寫入器：先扣住尾端 BUFFER_CHARS 字再吐出，
 * 讓封鎖樣式在跨 delta 邊界時也能被抓到。
 *
 * @param context 這次檢索到的題目與參考資料。**給了才做落地檢查**；
 *   不給的話行為與加入落地檢查之前完全一樣（既有測試就是這條的證據）。
 */
export function createGuardedWriter(
  emit: (text: string) => void,
  onBlocked: (matched: string) => void,
  context?: GuardContext
) {
  let pending = "";
  let full = "";
  let blocked = false;
  // 攔截屬於哪一類，供 finish() 回傳給呼叫端選替代回覆用。
  // 只在 blocked 由 false→true 的那一刻設一次，跟 blocked 同步，
  // 這樣就算 finish() 被呼叫第二次也還是報對第一次攔下來的原因。
  // pattern＝封鎖清單（政治表態、新承諾…）、leak＝推理外洩（第十五輪分出來）、privacy＝在世家人隱私與老師近況（第十輪分出來）、
  // grounding＝落地檢查。
  let blockedKind: GuardKind | undefined;

  return {
    push(delta: string) {
      if (blocked) return;
      pending += delta;
      full += delta;

      const check = checkAnswer(full);
      if (check.blocked) {
        blocked = true;
        blockedKind = check.kind ?? "pattern";
        onBlocked(check.matched ?? "unknown");
        return;
      }

      // 逗號後面的換行在切出要送的那一段之前先接起來（見 joinSoftBreaks）：
      // 逗號要離結尾 140 字以上才會被送出去，那時它後面的換行一定已經在 pending 裡，不會被切在兩段之間
      pending = joinSoftBreaks(pending);
      if (pending.length > BUFFER_CHARS) {
        const flushable = pending.slice(0, pending.length - BUFFER_CHARS);
        pending = pending.slice(pending.length - BUFFER_CHARS);
        emit(stripMarkdown(flushable));
      }
    },
    finish(): { text: string; blocked: boolean; kind?: GuardKind } {
      if (blocked) return { text: full, blocked: true, kind: blockedKind };

      // 🔴 第十二輪：有幾條樣式要看到後面真的出現的字才判得準（「照顧我」後面接什麼、英文的 chars／Let me），
      // push() 對還沒收完的文字比對時它們一律不中——那是刻意的（避免在半句話上誤攔）。
      // 整段收完之後，在句尾補一個換行當作「後面的字」再比對一次：答案剛好停在「…同住照顧我」、
      // 後面沒有標點的，在這裡接住。其餘樣式不看換行，結果跟 push() 最後一次一樣。
      const atEnd = checkAnswer(`${full}\n`);
      if (atEnd.blocked) {
        blocked = true;
        blockedKind = atEnd.kind ?? "pattern";
        pending = "";
        onBlocked(atEnd.matched ?? "unknown");
        return { text: full, blocked: true, kind: blockedKind };
      }

      if (context) {
        const verdict = groundingCheck(full, context);
        if (verdict.blocked) {
          blocked = true;
          blockedKind = "grounding";
          // 🔴 一定要在 emit 之前丟掉 pending。整段答案都還扣在緩衝裡，
          // 這一行就是「有出處才放行」真正生效的地方。
          pending = "";
          onBlocked(verdict.reason ?? "未落地");
          return { text: full, blocked: true, kind: "grounding" };
        }
      }

      if (pending) {
        emit(stripMarkdown(joinSoftBreaks(pending)));
        pending = "";
      }
      return { text: full, blocked: false };
    },
  };
}
