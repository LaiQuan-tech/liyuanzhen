describe("簡繁表", () => {
  /** 🔴「志」是正體字：原本在表裡，「我是志工」被換成「我是誌工」，開場白規則比對不到 */
  it("正體字不會被換掉", () => {
    expect(toTraditional("我是志工 同志 意志")).toBe("我是志工 同志 意志");
  });

  it("簡體的觸發詞與歷史題換得過去", () => {
    expect(toTraditional("妇女新知当年有被警总威胁过吗")).toBe("婦女新知當年有被警總威脅過嗎");
  });

  /**
   * 表裡的鍵（簡體字）一個都不能出現在規則裡——規則用正體寫，鍵一出現在規則裡，
   * 正體訪客打的那個字就會先被換掉、再也比對不到（「志工」就是這樣壞的）。
   * 掃 lib/crisis.ts 與 lib/smalltalk.ts 去掉註解與表本身之後的原始碼。
   */
  it("表裡的鍵不出現在任何規則裡", () => {
    const strip = (src: string) =>
      src
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .replace(/^\s*\/\/.*$/gm, "")
        .replace(/const S2T_PAIRS = `[\s\S]*?`/, "");
    const crisisSrc = readFileSync(resolve(__dirname, "crisis.ts"), "utf8");
    const code = strip(crisisSrc) + strip(readFileSync(resolve(__dirname, "smalltalk.ts"), "utf8"));
    const keys = crisisSrc.split("const S2T_PAIRS = `")[1].split("`")[0].trim().split(/\s+/).map((p) => p[0]);
    expect(keys.length).toBeGreaterThan(100);
    expect(keys.filter((k) => code.includes(k))).toEqual([]);
  });
});

