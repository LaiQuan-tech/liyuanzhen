describe("簡繁表", () => {
  /** 🔴「志」是正體字：原本在表裡，「我是志工」被換成「我是誌工」，開場白規則比對不到 */
  it("正體字不會被換掉", () => {
    expect(toTraditional("我是志工 同志 意志")).toBe("我是志工 同志 意志");
  });

  it("簡體的觸發詞與歷史題換得過去", () => {
    expect(toTraditional("妇女新知当年有被警总威胁过吗")).toBe("婦女新知當年有被警總威脅過嗎");
  });

  /**
   * 表裡的鍵（簡體字）一個都不能出現在規則裡——規則用正體寫，鍵一出現在規則裡，
   * 正體訪客打的那個字就會先被換掉、再也比對不到（「志工」就是這樣壞的）。
   * 掃 lib/crisis.ts 與 lib/smalltalk.ts 去掉註解與表本身之後的原始碼。
   */
  it("表裡的鍵不出現在任何規則裡", () => {
    const strip = (src: string) =>
      src
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .replace(/^\s*\/\/.*$/gm, "")
        .replace(/const S2T_PAIRS = `[\s\S]*?`/, "");
    const crisisSrc = readFileSync(resolve(__dirname, "crisis.ts"), "utf8");
    const code = strip(crisisSrc) + strip(readFileSync(resolve(__dirname, "smalltalk.ts"), "utf8"));
    const keys = crisisSrc.split("const S2T_PAIRS = `")[1].split("`")[0].trim().split(/\s+/).map((p) => p[0]);
    expect(keys.length).toBeGreaterThan(100);
    expect(keys.filter((k) => code.includes(k))).toEqual([]);
  });
});

/**
 * 專線救援（route 用）：落地檢查攔下的原答是在勸這位訪客打求助專線時，改送哪一類危機回覆。
 * 🔴 第三輪驗收：「我好痛苦」模型回了 1925，卻被換成「這一題我答不上來」。
 * 🔴 第四輪驗收：條件太寬，誤送 6 句正常提問——訪客自己要有痛苦字眼、號碼要在專線語境才算。
 */
describe("hotlineKind", () => {
  it.each([
    ["聽起來你很難受，可以打 1925 安心專線找人聊聊。", "self_harm"],
    ["也可以打 1995 生命線。", "self_harm"],
    ["張老師 1980 也可以。", "self_harm"], // 專線名稱＋號碼
    ["家暴、性侵害都可以打 113 保護專線。", "violence"],
    ["有危險請馬上打 110。", "violence"],
    ["可以打 1925，如果有人打你就打 113。", "self_harm"], // 兩種都有 → 自傷
    ["有立即危險請打 119。", "self_harm"],
  ] as const)("號碼在專線語境：%s → %s", (answer, kind) => {
    expect(hotlineKind(answer, "我好痛苦")).toBe(kind);
  });

  /** (c) 號碼不在專線語境：年份、年代、範圍、書名號；專線名稱單獨出現也不算 */
  it.each([
    "1995 年我在花蓮。",
    "1980 年代的婦運很辛苦。",
    "民國 110 年的修法。",
    "我在 1982 年創辦了婦女新知。",
    "我在 1980、1990 年代寫了很多雜文，第一本書是《飄泊的女人》。", // 第四輪驗收的誤送句
    "我小時候住左營眷村，民國 110 到 113 年住在臺北。",
    "劉毓秀主編的《台灣婦女處境白皮書：1995》，很多立委拿著它去質詢。",
    "另外張老師文化出過一本《女人的第二春》。", // 第四輪驗收的誤送句
    "遇到困難可以找張老師或生命線聊聊。", // 第四輪驗收的誤送句：有名稱沒有號碼
    "請務必尋求專業的求助專線。",
  ])("號碼不在專線語境：%s", (answer) => {
    expect(hotlineKind(answer, "我好痛苦")).toBeNull();
  });

  /** (b) 訪客這一句沒有第一人稱的痛苦或受害字眼：模型提專線只是在回答問題 */
  it.each([
    ["我老公外遇 我該離婚嗎", "如果心裡很難受，可以打 1925 安心專線，監護權的問題就找律師。"],
    ["妳對現在的年輕人有什麼建議？", "遇到困難不要一個人扛，可以打 1995 生命線。"],
    ["台灣的家暴防治是從什麼時候開始的？", "1998 年通過家暴法，後來政府設了 113 保護專線。"],
    ["我朋友想做志工，妳有推薦的團體嗎？", "可以去生命線當志工，生命線 1995 很需要人手。"],
    ["我不怕", "有需要可以打 1925 安心專線。"], // 「不怕」不算
  ])("訪客沒有痛苦字眼：%s", (question, answer) => {
    expect(hotlineKind(answer, question)).toBeNull();
  });

  it.each([
    "我最近好難過 每天都睡不著",
    "我先生最近脾氣很差 我很害怕",
    "我在學校一直被欺負",
  ])("訪客有痛苦或受害字眼：%s", (question) => {
    expect(hotlineKind("可以打 1925 安心專線。", question)).toBe("self_harm");
  });
});

