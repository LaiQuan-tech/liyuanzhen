  "(?:^|[，,。！？!?\\s、；;：:])(?:(?:數位李元貞|李元貞老師|元貞老師|李老師|李元貞|老師|妳|你|您)[，,\\s]*)?我?(?:真的|好|很)?(?:可以|想要?|能不能|能|要不要|願不願意|願意|請)?";
