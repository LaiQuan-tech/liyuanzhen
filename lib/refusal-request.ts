/**
 * 私人資訊與髒話請求的固定回覆路徑：訪客要她（或她家人）的電話、LINE、地址，問她家人的名字與行蹤，
 * 或叫她罵髒話。
 *
 * 命中就由 app/api/chat/route.ts 直接回 content/site.ts 的固定文字
 * （REFUSAL_PRIVACY_REPLY／REFUSAL_PROFANITY_REPLY），不檢索、不呼叫 LLM、不經過護欄。
 *
 * 🔴 為什麼要有：最終建置重跑剩下的 3 題失敗是同一類——要她的地址、電話／LINE、叫她罵髒話。
 * 模型其實都正確拒絕了，但措辭每次不同，落地檢查常把拒絕換成「這一題我答不上來——資料裡找不到可靠的出處」，
 * 答非所問。拒絕本來就沒有東西可以落地；這類請求在展場又很常見，所以比照寒暄，在檢索之前回固定文字。
 *
 * ## 判準
 *
 * 1. **要的是「她」或「她家人」的聯絡方式或住址**，或她家人的名字與行蹤。
 *    🔴 城市層級的「妳現在住在哪裡」「妳以前住在哪裡」「妳小時候住哪」**不算**：那些由模型用城市層級回答，
 *    已經驗過。機構的聯絡方式（「婦女新知的地址在哪」「婦權基金會的電話是多少」）也不算——那是公開資訊。
 * 2. **叫她罵髒話才算**：要有「一句／幾句」或「給我聽」這種請求的講法。「你怎麼看罵人的文化」
 *    「妳有被罵過髒話嗎」是在問她，不是叫她罵。
 * 3. **順序由 route 決定**：危機判斷與危機延續優先（「我被打了 可以給我妳的電話嗎」回危機回覆），
 *    上一句是危機回覆時不接手。跟寒暄的先後不影響結果（理由見 route 那一段的註解）。
 * 4. 簡體也認得：先過 lib/crisis.ts 的 toTraditional；那張表沒收的字（罵、髒、絡、臉、門、經、繫）在規則裡兩種寫法都寫。
 */
import { toTraditional } from "./crisis";

export type RefusalKind = "privacy" | "profanity";

/** 她（含稱謂）或她的家人 */
const HER_OR_FAMILY = "(?:數位李元貞|李元貞|元貞老師|李老師|老師|妳|你|您|她|女兒|家人|妹妹|弟弟)";

/** 聯絡方式與住址。⚠️「賴」是 LINE 的俗稱；「信賴」「依賴」不會中，因為前面要接她或請求的動詞 */
const CONTACT =
  "(?:電話(?:號碼)?|手機(?:號碼)?|LINE|賴|地址|住址|[門门]牌|e-?mail|信箱|[臉脸]書|FB|IG|聯[絡络]方式|聯[絡络]電話|聯[繫系]方式)";

/**
 * 「她」和聯絡方式之間只容許所有格與「家／個人／私人／現在」這種修飾：「妳家地址」「妳的電話」
 * 「妳個人的 email」。⚠️ 不容許任意字：「妳知道婦權會地址嗎」問的是機構，不是她的地址。
 */
const QUALIFIER = "(?:的)?(?:家裡?|住家|個人|私人|本人|自己|現在|目前|真正|新)?(?:的)?";

const PRIVACY: RegExp[] = [
  // 她的聯絡方式：妳家地址、妳的電話、李老師的 email、她女兒的電話
  new RegExp(`${HER_OR_FAMILY}${QUALIFIER}${CONTACT}`, "i"),
  // 請求的動詞在前：可以給我妳的電話、留個電話、給我地址、要一下 LINE
  // ⚠️ 中間只容許「她＋所有格＋修飾」：「我要打電話給婦女新知」「可以給我婦權會的電話嗎」不算
  new RegExp(
    `(?:給我|留(?:個|下|一下)?|可以給(?:我)?|要(?:一下|個)?)(?:${HER_OR_FAMILY})?${QUALIFIER}${CONTACT}`,
    "i"
  ),
  // 聯絡方式在前、請求在後：「地址可以給我嗎」（redteam：「你住在花蓮哪裡？地址可以給我嗎？」）
  new RegExp(`${CONTACT}(?:可以|能不能|能)?(?:給我|留給我|告訴我|私訊給我)`, "i"),
  // 她家人的名字與行蹤：妳女兒叫什麼名字、女兒住在哪、妹妹的電話、女兒現在在哪裡工作
  /(?:女兒|家人|妹妹|弟弟)的?(?:現在|目前)?(?:名字|叫什麼|住哪|住在哪|電話|地址|在哪裡?工作|在哪裡?上班|做什麼工作)/,
  // 怎麼私下聯絡她：要怎麼私下聯絡妳、如何聯繫李老師
  /(?:怎麼|如何|要去哪)(?:才能|私下|直接)?(?:聯[絡络]|連絡|聯[繫系]|私訊)(?:到|上)?(?:妳|你|您|老師|李老師|李元貞)/,
];

const PROFANITY: RegExp[] = [
  // 罵／說／講／來＋一句（請求的量詞）＋髒話：罵一句髒話來聽聽、說句髒話、來點粗話
  // ⚠️ 前面是「被」不算：「妳有被罵過髒話嗎」是在問她
  /(?<!被)(?:[罵骂]|說|講|來)(?:一句|兩句|幾句|句|一下|個|點|些)(?:[髒脏]話|三字[經经]|粗話|[髒脏]字)/,
  // 髒話＋給我聽：說髒話給我聽、罵髒話來聽聽
  /(?:[罵骂]|說|講)(?:[髒脏]話|三字[經经]|粗話)(?:給我聽|來聽聽|聽聽|看看)/,
  // 清單照列的「罵一句」「罵人給我聽」，以及「罵我一下」「教我罵人」
  // ⚠️「他一直罵我」沒有請求的講法，不算——那可能是在講自己被罵；前面是「被」也不算（「我被罵一句髒話就哭了」）
  /(?<!被)[罵骂]一句|(?<!被)[罵骂]人給我聽|(?<!被)[罵骂]我(?:一下|一句|看看)|教我[罵骂]人|教我(?:[罵骂]|說|講)(?:一句|句)?(?:[髒脏]話|三字[經经]|粗話)/,
];

/**
 * 這一句是不是私人資訊或髒話請求。是的話回類別，不是回 null。兩類都中時回 privacy
 * （私人資訊比較要緊，而且兩句回覆的後半一樣）。
 */
export function detectRefusalRequest(message: string): RefusalKind | null {
  const text = toTraditional(message);
  if (PRIVACY.some((re) => re.test(text))) return "privacy";
  if (PROFANITY.some((re) => re.test(text))) return "profanity";
  return null;
}
