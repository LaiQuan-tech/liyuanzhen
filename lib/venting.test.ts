/**
 * 🔴 審查實測：DEG 同時收「每天都」與「每天」「都」、ADVERBIAL_GAP 同時收「常常」與「常」時會指數回溯——
 * 「每天都」×22 就要 0.6 秒、每多一組翻倍，300 字的特製輸入能把請求卡到 30 秒逾時（紀錄也寫不進去）。
 * 這裡的每一句在修正前都跑不完；修正後都是毫秒級。上限抓得很寬，只擋指數回溯，不量效能。
 */
describe("detectVenting：特製輸入不會卡住", () => {
  it.each([
    ["每天都×95＋X-07", "每天都".repeat(95) + "喔 我媽一直逼我結婚 好煩喔"],
    ["天天都×99", "天天都".repeat(99) + "X"],
    ["壓力＋每天都×99", "壓力" + "每天都".repeat(99) + "X"],
    ["我媽＋常×290", "我媽" + "常".repeat(290) + "X好累"],
    ["好×300", "好".repeat(300)],
    ["心＋好×297", "心" + "好".repeat(297) + "X"],
  ])("%s", (_label, q) => {
    const t0 = performance.now();
    detectVenting(q);
    expect(performance.now() - t0).toBeLessThan(500);
  });
});

