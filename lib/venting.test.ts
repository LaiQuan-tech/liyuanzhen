/** 需求列的正例：X-07 原句＋三句 */
const REQUIRED = ["我媽一直逼我結婚 好煩喔", "我老公都不做家事 好累", "工作壓力好大 快受不了了", "我好委屈 婆婆一直唸我"];

/** 需求列的反例：問她事情的句子、講別人的 */
const REQUIRED_NOT = ["妳當年壓力大嗎", "婦運很累嗎", "妳會煩惱嗎", "我媽說她很累"];

describe("detectVenting：需求列的正反例", () => {
  it.each(REQUIRED)("抒發：%s", (q) => {
    expect(detectVenting(q)).not.toBeNull();
  });

  it.each(REQUIRED_NOT)("不是抒發：%s", (q) => {
    expect(detectVenting(q)).toBeNull();
  });

  it("命中的是那段感受（給 log 看）", () => {
    expect(detectVenting("我媽一直逼我結婚 好煩喔")).toBe("好煩");
    expect(detectVenting("工作壓力好大 快受不了了")).toBe("壓力好大");
  });
});

