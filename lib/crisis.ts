/** 把簡體字換成繁體（只換 S2T_PAIRS 收的字）。lib/smalltalk.ts 也用這支。 */
export function toTraditional(text: string): string {
  return Array.from(text, (c) => TO_TRADITIONAL.get(c) ?? c).join("");
}

