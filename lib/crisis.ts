/** 一條觸發規則。`re` 一律帶 g：同一個子句裡前一個命中被排除時，後一個還要能被看到。 */
interface Rule {
  re: RegExp;
  /**
   * 只有整句有「我」、有求助語、或有第一人稱受害陳述時才算數。給本身不帶受害者的詞用：
   * 「家暴」單獨出現可能是在談議題，「我老公會家暴」「家暴怎麼辦」才是求助。
   */
  firstPersonOnly?: boolean;
}

